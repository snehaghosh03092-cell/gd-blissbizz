"""Seed tenants and their catalogs (FICTIONAL sample data).

Each product carries a demand *persona* that the simulator turns into sales history and stock levels, so the
resulting data supports many kinds of questions (best sellers, stock-outs, dead stock, surplus, trends...):

BEST      high demand, restocked automatically        STEADY    normal demand, restocked
SLOW      low demand, large overstock                  LOW       demand ok, stock now at/below reorder level
STOCKOUT  sold out some days ago, PO overdue           DEAD      no sales for 65+ days, stock remains
NEW       launched ~12 days ago                        LAUNCH    launched ~8 days ago, hot, nearly sold out
SEASONAL  demand ramping up (festive/winter)           DECLINING demand falling over the period
ARCHIVED  discontinued, stock remains                  DRAFT     unpublished, no sales
"""

from dataclasses import dataclass, field
from decimal import Decimal

from app.core.gstin import with_checksum


@dataclass
class P:
    name: str
    cat: str
    brand: str
    price: float
    tax: str
    hsn: str
    persona: str = "STEADY"
    unit: str = "PCS"
    sizes: list[str] | None = None
    colors: list[str] | None = None
    packs: list[tuple[str, float, float]] | None = (
        None  # (label, price multiplier, popularity weight)
    )
    desc: str = ""
    cost: float = 0.55
    sup: int = 0


@dataclass
class BusinessSpec:
    key: str
    name: str
    legal_name: str
    category: str
    constitution: str
    sales_mode: str
    city: str
    state_code: str
    postal_code: str
    address: str
    template: str
    theme: dict
    invoice_prefix: str
    gst_registered: bool
    gstin: str | None
    prices_include_tax: bool
    orders_per_day: float
    lines_mean: float
    cod_share: float
    customers: int
    warehouses: list[tuple[str, str, str]]  # (code, name, city)
    suppliers: list[tuple[str, int, int]]  # (name, lead_days, payment_terms_days)
    products: list[P] = field(default_factory=list)
    policy: dict = field(default_factory=dict)
    growth: float = 0.15
    home_share: float = 0.55
    free_shipping_over: Decimal = Decimal("999")
    flat_shipping: Decimal = Decimal("49")
    active: bool = True
    status: str = "ACTIVE"
    onboarding_state: str = "ACTIVE"


def _gstin(state: str, pan: str, entity: str = "1") -> str:
    return with_checksum(f"{state}{pan}{entity}Z")


